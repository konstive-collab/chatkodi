"""Diverse evaluation corpus: different document kinds, formats and question types.

Unlike tools/synthetic_corpus.py (one report template, generated questions),
the documents here are hand-written: a supply contract, an order, meeting
minutes, an equipment manual, a price list and a vacation schedule (xlsx),
an incident memo, a customer complaint (e-mail), quarterly results (pptx) and
a travel policy. Questions and gold answers live in ``tools/diverse_cases.json``
and were checked against these texts by hand.

    python -m tools.diverse_corpus --out <folder>     # writes <folder>/docs and cases.json
    python tools/eval_synthetic.py --corpus <folder> --with-llm
"""

