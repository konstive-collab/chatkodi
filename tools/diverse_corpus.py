def write_corpus(out_dir: Path) -> Path:
    docs = out_dir / "docs"
    if docs.exists():
        shutil.rmtree(docs)
    docs.mkdir(parents=True)
    for writer in (_write_contract, _write_order, _write_minutes, _write_manual, _write_incident,
                   _write_tables, _write_complaint, _write_results, _write_policy):
        writer(docs)
    cases = json.loads(CASES_FILE.read_text(encoding="utf-8"))
    (out_dir / "cases.json").write_text(json.dumps(cases, ensure_ascii=False, indent=2), encoding="utf-8")
    return docs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    out = Path(args.out).resolve()
    docs = write_corpus(out)
    cases = json.loads((out / "cases.json").read_text(encoding="utf-8"))["cases"]
    print(json.dumps({"ok": True, "docs": str(docs), "documents": len(list(docs.iterdir())), "cases": len(cases)}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
