def _docx(path: Path, paragraphs: list[str], table: list[list[str]] | None = None) -> None:
    from docx import Document

    doc = Document()
    for text in paragraphs:
        if text.startswith("# "):
            doc.add_heading(text[2:], level=1)
        else:
            doc.add_paragraph(text)
    if table:
        grid = doc.add_table(rows=len(table), cols=len(table[0]))
        for r, row in enumerate(table):
            for c, value in enumerate(row):
                grid.cell(r, c).text = value
    doc.save(str(path))


def _xlsx(path: Path, sheet: str, rows: list[list[object]]) -> None:
    from openpyxl import Workbook

    wb = Workbook()
    ws = wb.active
    ws.title = sheet
    for row in rows:
        ws.append(row)
    wb.save(str(path))


def _pptx(path: Path, slides: list[tuple[str, list[str]]]) -> None:
    from pptx import Presentation

    prs = Presentation()
    for title, lines in slides:
        slide = prs.slides.add_slide(prs.slide_layouts[1])
        slide.shapes.title.text = title
        body = slide.placeholders[1].text_frame
        body.text = lines[0]
        for line in lines[1:]:
            body.add_paragraph().text = line
    prs.save(str(path))


